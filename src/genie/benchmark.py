"""Run the Task 9 benchmark against the Genie space through the Conversation API.

    python src/genie/benchmark.py --run-label "run 1"

Each question in benchmark_questions.yaml starts a new conversation, is polled until it
completes, and its query result is fetched. Pass = Genie returned SQL and a non-empty result;
questions marked `subset_of_persona_opps` must also only return opportunities owned by the
caller's persona (derived with SQL from gold_opportunity_pipeline, ruling R14).

Every run is saved as evidence/08_genie_runs/<n>.json and evidence/08_genie.md is rebuilt from
all saved runs, so earlier runs stay in the evidence.
"""

import argparse
import json
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

import yaml

sys.path.insert(0, str(Path(__file__).resolve().parent))
from common import GENIE_DIR, ROOT, SPACE_ID_FILE, TITLE, default, workspace_client  # noqa: E402

QUESTIONS_FILE = GENIE_DIR / "benchmark_questions.yaml"
RUNS_DIR = ROOT / "evidence" / "08_genie_runs"
EVIDENCE = ROOT / "evidence" / "08_genie.md"
TERMINAL = {"COMPLETED", "FAILED", "CANCELLED", "QUERY_RESULT_EXPIRED"}
PASS_TARGET = 8
CELL_MAX = 60


# --------------------------------------------------------------------------- pure helpers


def load_questions(path: Path = QUESTIONS_FILE) -> list[dict]:
    qs = yaml.safe_load(path.read_text())["questions"]
    ids = [q["id"] for q in qs]
    if len(ids) != len(set(ids)):
        raise ValueError("duplicate question ids")
    return qs


def extract_answer(message: dict) -> dict:
    """SQL, query attachment id and any text reply from a get-message response (as a dict)."""
    out = {"sql": None, "attachment_id": None, "text": None, "description": None}
    for att in message.get("attachments") or []:
        query = att.get("query")
        if query and query.get("query") and not out["sql"]:
            out.update(sql=query["query"], attachment_id=att.get("attachment_id"),
                       description=query.get("description"))
        text = (att.get("text") or {}).get("content")
        if text and not out["text"]:
            out["text"] = text
    return out


def result_rows(result: dict) -> tuple[list[str], list[list]]:
    """Column names and rows from a get-message-attachment-query-result response (as a dict)."""
    sr = result.get("statement_response") or {}
    cols = [c["name"] for c in ((sr.get("manifest") or {}).get("schema") or {}).get("columns") or []]
    rows = (sr.get("result") or {}).get("data_array") or []
    return cols, rows


def check_subset(cols: list[str], rows: list[list], persona_opps: dict[str, str]) -> tuple[bool, str]:
    """Every returned opportunity must be one of the persona's (by opportunity_id, else name).

    persona_opps maps opportunity_id -> opportunity_name.
    """
    for col, allowed in (("opportunity_id", set(persona_opps)), ("opportunity_name", set(persona_opps.values()))):
        if col in cols:
            i = cols.index(col)
            outside = sorted({r[i] for r in rows} - allowed)
            if outside:
                return False, f"{len(outside)} {col}(s) not in the persona's opportunities: {outside[:3]}"
            return True, f"all {len({r[i] for r in rows})} {col}(s) are the persona's"
    return False, "result has no opportunity_id/opportunity_name column to verify scope"


def grade(question: dict, answer: dict, cols: list[str], rows: list[list], status: str,
          persona_opps: dict[str, str]) -> tuple[bool, str]:
    if status != "COMPLETED":
        return False, f"message {status}"
    if not answer.get("sql"):
        return False, "no SQL generated" + (f" (Genie replied: {answer['text'][:120]})" if answer.get("text") else "")
    if not rows:
        return False, "SQL returned no rows"
    if question.get("subset_of_persona_opps"):
        return check_subset(cols, rows, persona_opps)
    return True, f"{len(rows)} row(s)"


def _cell(v) -> str:
    s = "NULL" if v is None else str(v)
    s = s.replace("|", "\\|").replace("\n", " ")
    return s if len(s) <= CELL_MAX else s[: CELL_MAX - 1] + "…"


def md_table(cols: list[str], rows: list[list], limit: int = 5) -> str:
    if not cols:
        return "_(no result)_"
    lines = ["| " + " | ".join(_cell(c) for c in cols) + " |", "|" + "---|" * len(cols)]
    lines += ["| " + " | ".join(_cell(v) for v in r) + " |" for r in rows[:limit]]
    if not rows:
        lines.append("| " + " | ".join("" for _ in cols) + " |")
    return "\n".join(lines)


def render_markdown(runs: list[dict], target: int = PASS_TARGET) -> str:
    out = [
        "# Evidence 08: Genie Agent \"Fleetwise Revenue Copilot\" (Task 9)",
        "",
        "Generated by `src/genie/benchmark.py` (Genie Conversation API: start-conversation, poll "
        "get-message, get-message-attachment-query-result). Each question runs in a new "
        f"conversation. Pass = SQL generated and a non-empty result; Q2 must also stay inside the "
        f"caller's persona's opportunities. Target: >= {target}/10. All runs are kept (oldest first).",
        "",
        "| Run | When (UTC) | Caller -> persona | Passed | Median latency (s) |",
        "|---|---|---|---|---|",
    ]
    for run in runs:
        lat = sorted(r["latency_s"] for r in run["results"])
        med = lat[len(lat) // 2] if lat else 0
        out.append(f"| {run['label']} | {run['started_at']} | {run['caller']} -> {run['persona']} | "
                   f"{run['passed']}/{len(run['results'])} | {med:.1f} |")
    for run in runs:
        out += ["", f"## {run['label']}: {run['passed']}/{len(run['results'])} passed", "",
                f"Space `{run['space_id']}`. {run.get('note') or ''}".rstrip()]
        for r in run["results"]:
            out += ["", f"### {r['id']}. {r['question']}", "",
                    f"**{'PASS' if r['passed'] else 'FAIL'}** ({r['reason']}). Status {r['status']}, "
                    f"latency {r['latency_s']:.1f} s, {r['row_count']} row(s).", ""]
            if r.get("text"):
                out += [f"> {_cell(r['text']) if len(r['text']) > 400 else r['text'].replace(chr(10), ' ')}", ""]
            out += ["```sql", (r.get("sql") or "-- no SQL").strip(), "```", "", md_table(r["columns"], r["rows"])]
    return "\n".join(out) + "\n"


# --------------------------------------------------------------------------- live calls


def ask(w, space_id: str, question: str, timeout_s: int = 300) -> dict:
    t0 = time.monotonic()
    started = w.genie.start_conversation(space_id, question)  # returns a waiter; we poll ourselves
    conv_id, msg_id = started.response.conversation_id, started.response.message_id
    while True:
        msg = w.genie.get_message(space_id, conv_id, msg_id).as_dict()
        if msg.get("status") in TERMINAL:
            break
        if time.monotonic() - t0 > timeout_s:
            msg["status"] = "TIMEOUT"
            break
        time.sleep(2)
    answer = extract_answer(msg)
    cols, rows = [], []
    if msg.get("status") == "COMPLETED" and answer["attachment_id"]:
        res = w.genie.get_message_attachment_query_result(space_id, conv_id, msg_id, answer["attachment_id"])
        cols, rows = result_rows(res.as_dict())
    error = msg.get("error")
    if error and not answer["text"]:
        answer["text"] = f"error: {error}"
    return {"status": msg.get("status"), "latency_s": time.monotonic() - t0, "conversation_id": conv_id,
            "message_id": msg_id, "columns": cols, "all_rows": rows, **answer}


def persona_context(w, warehouse_id: str, catalog: str, schema: str) -> tuple[str, str, dict[str, str]]:
    """Caller, their persona name, and the persona's opportunities from the BASE table (R14)."""
    fq = f"`{catalog}`.`{schema}`"
    stmt = (
        f"SELECT current_user() AS caller, h.name AS persona, p.opportunity_id, p.opportunity_name "
        f"FROM {fq}.demo_identity_map m JOIN {fq}.gold_user_hierarchy h ON h.user_id = m.persona_user_id "
        f"LEFT JOIN {fq}.gold_opportunity_pipeline p ON p.owner_id = m.persona_user_id "
        f"WHERE m.workspace_email = current_user()"
    )
    resp = w.statement_execution.execute_statement(statement=stmt, warehouse_id=warehouse_id, wait_timeout="50s")
    if resp.status.state.value != "SUCCEEDED":
        raise RuntimeError(f"persona lookup failed: {resp.status}")
    rows = resp.result.data_array or []
    if not rows:
        raise RuntimeError("the caller has no demo_identity_map row; run the job's apply_governance task")
    return rows[0][0], rows[0][1], {r[2]: r[3] for r in rows if r[2]}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--run-label", required=True)
    ap.add_argument("--note", default="", help="free text recorded with the run (e.g. what was tuned)")
    ap.add_argument("--catalog", default=default("catalog", "FLEETWISE_CATALOG"))
    ap.add_argument("--schema", default=default("schema", "FLEETWISE_SCHEMA"))
    ap.add_argument("--warehouse-id", default=default("warehouse_id", "FLEETWISE_WAREHOUSE_ID"))
    ap.add_argument("--profile", default=default("profile", "DATABRICKS_CONFIG_PROFILE"))
    ap.add_argument("--space-id", default=None, help=f"default: {SPACE_ID_FILE.name}")
    args = ap.parse_args(argv)
    space_id = args.space_id or SPACE_ID_FILE.read_text().strip()
    w = workspace_client(args.profile)
    caller, persona, opps = persona_context(w, args.warehouse_id, args.catalog, args.schema)
    print(f"{TITLE} {space_id}: caller {caller} -> persona {persona} ({len(opps)} opps)")

    run = {"label": args.run_label, "note": args.note, "space_id": space_id, "caller": caller,
           "persona": persona, "started_at": datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M"),
           "results": []}
    for q in load_questions():
        try:
            a = ask(w, space_id, q["question"])
        except Exception as e:  # record and continue: one failed call must not lose the run
            a = {"status": "ERROR", "latency_s": 0.0, "columns": [], "all_rows": [], "sql": None,
                 "text": f"{type(e).__name__}: {e}"}
        passed, reason = grade(q, a, a["columns"], a["all_rows"], a["status"], opps)
        run["results"].append({
            "id": q["id"], "question": q["question"], "passed": passed, "reason": reason,
            "status": a["status"], "latency_s": round(a["latency_s"], 1), "sql": a.get("sql"),
            "text": a.get("text"), "columns": a["columns"], "rows": a["all_rows"][:5],
            "row_count": len(a["all_rows"]),
        })
        print(f"  {q['id']}: {'PASS' if passed else 'FAIL'} ({reason}) {a['latency_s']:.1f}s")
    run["passed"] = sum(r["passed"] for r in run["results"])

    RUNS_DIR.mkdir(parents=True, exist_ok=True)
    n = len(list(RUNS_DIR.glob("run*.json"))) + 1
    (RUNS_DIR / f"run{n}.json").write_text(json.dumps(run, indent=2, default=str) + "\n")
    runs = [json.loads(p.read_text()) for p in sorted(RUNS_DIR.glob("run*.json"), key=lambda p: int(p.stem[3:]))]
    EVIDENCE.write_text(render_markdown(runs))
    print(f"{run['passed']}/{len(run['results'])} passed -> {EVIDENCE.relative_to(ROOT)}")
    return 0 if run["passed"] >= PASS_TARGET else 1


if __name__ == "__main__":
    sys.exit(main())
